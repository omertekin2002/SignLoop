import { describe, expect, it, vi } from "vitest";
import { PDFDocument } from "pdf-lib";
import type { ToolSet } from "ai";
import { createContractEgressGuard } from "@repo/chat-engine/chat-tools";
import { generateChatFile } from "./chat-file-generation";
import { chatDocumentExtension } from "./chat-document-tools";
import { processFile } from "./text-extraction";
import { CHAT_FILE_TYPES } from "./chat-files-shared";

const content =
  "# Review notes\nİstanbul — sözleşme özeti\n- Payment is due within thirty days.\n- The renewal notice period is sixty days.\n\nA longer explanatory paragraph preserves readable text in every output format.";

describe("downloadable chat documents", () => {
  it.each(["pdf", "txt", "docx"] as const)(
    "creates a real %s which the upload extractor can read again",
    async (format) => {
      const file = await generateChatFile({
        name: "Review notes",
        format,
        content,
      });
      const bytes = Buffer.from(file.data, "base64");
      expect(bytes.length).toBe(file.size);
      expect(file.name).toBe(`Review notes.${format}`);
      const read = await processFile(bytes, CHAT_FILE_TYPES[format], file.name);
      expect(read.text).toContain("İstanbul");
      expect(read.text).toContain("Payment is due within thirty days.");
      expect(read.text).toContain("sixty days");
    },
  );

  it("paginates long PDFs and refuses missing glyphs instead of corrupting text", async () => {
    const file = await generateChatFile({
      name: "Long notes",
      format: "pdf",
      content: "This paragraph is repeated across multiple pages.\n".repeat(
        180,
      ),
    });
    expect(
      (await PDFDocument.load(Buffer.from(file.data, "base64"))).getPageCount(),
    ).toBeGreaterThan(2);
    await expect(
      generateChatFile({ name: "Notes", format: "pdf", content: "日本語" }),
    ).rejects.toThrow("DOCX or TXT");
  });

  it("bounds content and sanitizes filenames", async () => {
    const file = await generateChatFile({
      name: "../../notes\r\n.txt",
      format: "txt",
      content: "Hello",
    });
    expect(file.name).not.toMatch(/[\r\n/\\]/);
    await expect(
      generateChatFile({
        name: "notes",
        format: "txt",
        content: "x".repeat(60_001),
      }),
    ).rejects.toThrow("60,000");
  });
});

// Exercise the same executable tool definition used by ToolLoopAgent, without a provider call.
async function execute(tools: ToolSet, name: string, input: unknown) {
  const run = tools[name]!.execute!;
  return run(input as never, { toolCallId: "tool-1", messages: [], context: {} });
}

describe("chat document tools", () => {
  const id = "11e3e947-f71f-4ecd-a901-adbf24edbb8a";
  const text =
    "The private agreement contains confidential negotiated payment terms. ".repeat(
      300,
    );
  const file = {
    id,
    name: "Agreement.txt",
    mediaType: "text/plain",
    size: text.length,
    text,
  };
  const build = () => {
    const onFile = vi.fn();
    const egressGuard = createContractEgressGuard();
    const extension = chatDocumentExtension([file], onFile);
    const tools = extension.createTools!({
      signal: new AbortController().signal,
      egressGuard,
      onEvidence: vi.fn(),
      onContractEvidence: vi.fn(),
    });
    return { tools, onFile, egressGuard };
  };

  it("reads bounded windows, carries offsets, and protects document wording from outbound research", async () => {
    const { tools, egressGuard } = build();
    const result = await execute(tools, "read_file", { fileId: id });
    expect(result).toMatchObject({
      offset: 0,
      nextOffset: 12_000,
      characterCount: text.length,
    });
    expect(String((result as { content: string }).content)).toContain(
      "UNTRUSTED CONTENT",
    );
    expect(
      egressGuard.check(
        "The private agreement contains confidential negotiated payment terms",
      ),
    ).toHaveProperty("error");
    expect(
      await execute(tools, "read_file", { fileId: crypto.randomUUID() }),
    ).toHaveProperty("error");
  });

  it("attaches generated bytes outside tool replay and enforces the per-turn budget", async () => {
    const { tools, onFile } = build();
    const input = {
      name: "notes",
      format: "txt",
      content: "A useful summary.",
    };
    const result = await execute(tools, "create_file", input);
    expect(result).toMatchObject({ status: "attached", name: "notes.txt" });
    expect(result).not.toHaveProperty("data");
    expect(onFile.mock.calls[0]![0]).toHaveProperty("data");
    await execute(tools, "create_file", input);
    expect(await execute(tools, "create_file", input)).toHaveProperty("error");
    expect(onFile).toHaveBeenCalledTimes(2);
  });
});
